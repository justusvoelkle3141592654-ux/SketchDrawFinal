// Built-in, original, procedural brush presets. All values are hand-tuned for Canvas Forge.
import type { CurvePoint } from '../curve';
import { CURVE_PRESETS, LINEAR_CURVE } from '../curve';
import {
  createBrush,
  type BrushPreset,
  type DynamicsInput,
  type DynamicsMapping,
  type DynamicsOutput,
} from './schema';

const DESC: CurvePoint[] = [
  { x: 0, y: 1 },
  { x: 0.5, y: 0.5 },
  { x: 1, y: 0 },
];

let n = 0;
function map(
  input: DynamicsInput,
  output: DynamicsOutput,
  amount: number,
  curve: CurvePoint[] = LINEAR_CURVE,
): DynamicsMapping {
  return { id: `m${++n}`, enabled: true, input, output, amount, curve };
}
const pSize = (a: number, c?: CurvePoint[]) => map('pressure', 'size', a, c);
const pOpacity = (a: number, c?: CurvePoint[]) => map('pressure', 'opacity', a, c);
const pFlow = (a: number, c?: CurvePoint[]) => map('pressure', 'flow', a, c);
const followDirection = () => map('direction', 'angle', 1);
const speedThin = (a: number) => map('speed', 'size', a, DESC);

type Def = Partial<BrushPreset> & { id: string; name: string; category: BrushPreset['category'] };

function preset(d: Def): BrushPreset {
  const b = createBrush({
    ...d,
    factory: true,
    author: 'Canvas Forge',
    created: '2026-10-15T00:00:00.000Z',
    modified: '2026-10-15T00:00:00.000Z',
  });
  return b;
}

